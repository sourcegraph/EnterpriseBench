"""Render the findings report from the analysis JSON, not from prose.

Every number in the report is read out of `comparison.json`, `trace_stats.json`
and `traces.json` at render time. Nothing is transcribed by hand, so the report
cannot drift from the corpus it describes -- re-running the sweep and
re-rendering is the only way to change a figure in it.

The report's structure follows the brief's four claims, which stay in separate
sections on purpose: preference, retrieval quality, end-task outcome, and cost.

Usage:
    python3 render_findings.py --out FINDINGS.md
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def _f(value, spec=".3f", dash="n/a"):
    return dash if value is None else format(value, spec)


def _table(rows: list[list[str]], header: list[str]) -> str:
    lines = ["| " + " | ".join(header) + " |",
             "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def quality_table(comparison: dict) -> str:
    rows = []
    for name, row in sorted(comparison["conditions"].items()):
        rows.append([
            name, row.get("knows") or "", str(row["n_tasks"]), str(row["n_runs"]),
            _f((row.get("completion") or {}).get("completion_rate"), ".2f"),
            _f(row["file_recall"]), _f(row["file_precision"]), _f(row["file_f1"]),
            _f(row["within_task_recall_sd"]),
        ])
    return _table(rows, ["condition", "knows", "tasks", "runs", "completed",
                         "recall", "precision", "F1", "within-task sd"])


def cost_table(comparison: dict) -> str:
    rows = []
    for name, row in sorted(comparison["conditions"].items()):
        rows.append([
            name, _f(row.get("cost_usd"), ".3f"),
            _f(row.get("input_tokens"), ",.0f"), _f(row.get("output_tokens"), ",.0f"),
            _f(row.get("wall_seconds"), ".1f"), _f(row.get("tool_seconds"), ".2f"),
            _f(row.get("retrieval_result_chars"), ",.0f"),
        ])
    return _table(rows, ["condition", "USD/run", "input tok", "output tok",
                         "wall s", "tool s", "result chars"])


def contrast_table(comparison: dict) -> str:
    rows = []
    for name, row in comparison["contrasts"].items():
        low, high = row["ci95"]
        separated = "yes" if row["excludes_zero"] else "no"
        rows.append([name, _f(row["mean_difference"], "+.3f"),
                     f"[{low:+.3f}, {high:+.3f}]", str(row["n_tasks"]), separated])
    return _table(rows, ["contrast (recall)", "difference", "CI95", "tasks",
                         "excludes 0"])


def preference_table(stats: dict) -> str:
    rows = []
    for name, row in sorted(stats.items()):
        unused = "; ".join(
            f"{tool} {v['runs_unused']}/{v['runs_offered']}"
            for tool, v in row["offered_but_never_used"].items()
        )
        rows.append([
            name,
            ", ".join(f"{k}={v}" for k, v in sorted(row["first_primitive"].items())),
            _f(row["mean_total_calls"], ".1f"),
            _f(row["mean_first_relevant_call"], ".1f"),
            f"{row['runs_reaching_sufficient_evidence']}/{row['n_runs']}",
            _f(row["mean_irrelevant_files_read"], ".1f"),
            unused or "-",
        ])
    return _table(rows, ["condition", "first primitive", "calls",
                         "first relevant call", "sufficient evidence",
                         "irrelevant reads", "offered but never used"])


def category_table(comparison: dict) -> str:
    conditions = sorted(comparison["conditions"])
    categories = sorted({
        c for row in comparison["conditions"].values() for c in row["by_category"]
    })
    rows = []
    for category in categories:
        cells = []
        for name in conditions:
            entry = comparison["conditions"][name]["by_category"].get(category)
            cells.append(_f(entry["file_recall"]) if entry else "-")
        n = max(
            (comparison["conditions"][c]["by_category"].get(category) or {}).get("n_runs", 0)
            for c in conditions
        )
        rows.append([category, str(n)] + cells)
    return _table(rows, ["category", "runs/cond"] + conditions)


def render(comparison: dict, stats: dict, traces: dict) -> str:
    seam = comparison.get("generation_seam")
    return f"""# Structural search vs precise code intelligence: pilot findings

Generated by `render_findings.py` from `comparison.json`, `trace_stats.json`
and `traces.json`. Do not edit numbers here; re-render.

Generation seam: `{seam}`. Scoring contract: `{comparison['scoring']}`.
Uncertainty: paired bootstrap over tasks, {comparison['bootstrap_samples']}
samples, seed {comparison['bootstrap_seed']}; repeats of a task are averaged
before resampling, because repeats are not independent observations.

Runs excluded from the quality means because they produced no score:
{comparison['unscored_runs_excluded']}.

## Claim 1 -- what agents PREFER

{preference_table(stats)}

## Claim 2 -- what RETRIEVES the best evidence

{quality_table(comparison)}

{contrast_table(comparison)}

### By task category (file recall)

{category_table(comparison)}

## Claim 3 -- what produces the best END-TASK outcome

{comparison['end_task_reward']}

## Claim 4 -- what is CHEAPEST and FASTEST

{cost_table(comparison)}

## Representative traces

Selected by rule, not by hand ({traces['n_traces']} traces in `traces.json`);
the conditions disagree most on `{traces['most_divergent_task']}`.
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--comparison", type=Path, default=HERE / "comparison.json")
    parser.add_argument("--stats", type=Path, default=HERE / "trace_stats.json")
    parser.add_argument("--traces", type=Path, default=HERE / "traces.json")
    parser.add_argument("--out", type=Path, default=HERE / "FINDINGS.md")
    args = parser.parse_args()

    text = render(
        json.loads(args.comparison.read_text()),
        json.loads(args.stats.read_text()),
        json.loads(args.traces.read_text()),
    )
    args.out.write_text(text)
    print(f"{args.out} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
